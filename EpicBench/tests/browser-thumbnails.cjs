'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { start } = require('../server');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'epic-thumbnail-browser-'));
const artifacts = path.join(__dirname, 'artifacts'); fs.mkdirSync(artifacts, { recursive: true });
let service, browser;
(async () => {
  service = await start({ port: 0, root: temp, archiveRoot: path.join(temp, 'archive'), communityDataDir: path.join(temp, 'db') });
  const base = 'http://127.0.0.1:' + service.port;
  browser = await chromium.launch({ headless: true, ...(process.env.COMMUNITY_CHROME_PATH ? { executablePath: process.env.COMMUNITY_CHROME_PATH } : {}) });
  const page = await browser.newPage(); page.setDefaultTimeout(35000);
  await page.goto(base + '/Community/');
  const identity = await page.evaluate(async () => (await fetch('/api/community/v1/auth/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'thumbnail-tester', password: 'private-thumbnail-test-password' }) })).json());
  const project = await page.evaluate(async csrf => (await (await fetch('/api/community/v1/projects', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf }, body: JSON.stringify({ name: 'Thumbnail verification', url: 'https://example.com', visibility: 'unlisted' }) })).json()).project, identity.csrfToken);
  assert.equal(project.thumbnailSource, 'automatic');
  await page.goto(base + '/Community/projects/' + project.slug);
  await page.waitForFunction(() => [...document.images].some(image => image.src.includes('/thumbnail?') && image.naturalWidth === 1280), { timeout: 35000 });
  await page.screenshot({ path: path.join(artifacts, 'automatic-thumbnail.png') });
  console.log('PASS actual URL screenshot generated, served and rendered in project detail');
  await page.goto(base + '/Community/publish?edit=' + project.id);
  // Generate a distinct real upload with the browser, independent of the capture.
  const encoded = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 800; c.height = 450; const g = c.getContext('2d'); g.fillStyle = '#3253cc'; g.fillRect(0,0,800,450); g.fillStyle = 'white'; g.font = '52px sans-serif'; g.fillText('My custom thumbnail',70,240); return c.toDataURL('image/png').split(',')[1]; });
  await page.locator('#thumbnailUpload').setInputFiles({ name: 'my-cover.png', mimeType: 'image/png', buffer: Buffer.from(encoded, 'base64') });
  await page.getByText('Image selected. Save your project to keep this thumbnail.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.waitForURL('**/Community/projects/' + project.slug);
  const read = () => page.evaluate(async id => (await (await fetch('/api/community/v1/projects/' + id)).json()).project, project.id);
  assert.equal((await read()).thumbnailSource, 'upload');
  await page.waitForFunction(() => [...document.images].some(image => image.src.includes('/thumbnail?') && image.naturalWidth === 800));
  await page.goto(base + '/Community/publish?edit=' + project.id);
  await page.getByText('Your uploaded thumbnail is saved. You can replace it below.', { exact: true }).waitFor();
  await page.getByLabel('Project name', { exact: false }).fill('Updated thumbnail project');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.waitForURL('**/Community/projects/' + project.slug);
  assert.equal((await read()).thumbnailSource, 'upload');
  console.log('PASS image upload, save, display and preservation through later edits');
  await page.goto(base + '/Community/publish?edit=' + project.id);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(artifacts, 'thumbnail-editor-mobile.png'), fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Use automatic preview', exact: true }).click();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.waitForURL('**/Community/projects/' + project.slug);
  assert.equal((await read()).thumbnailSource, 'automatic');
  await page.waitForFunction(() => [...document.images].some(image => image.src.includes('/thumbnail?') && image.naturalWidth === 1280));
  console.log('PASS mobile editor and switching back to a fresh automatic screenshot');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  await browser?.close(); await service?.close();
  if (path.resolve(temp).startsWith(path.resolve(os.tmpdir()) + path.sep)) fs.rmSync(temp, { recursive: true, force: true });
});
